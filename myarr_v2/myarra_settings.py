def check_llm(timeout=5):
    """Ping the LLM and return (ok, detail).

    Called at startup by the web app and the bot, and shown on
    /setup/verify. Without it a wrong LLM_URL is invisible: ask.py shows
    an error, herbie.py silently falls back to a template, and intent.py
    leaves the bot answering "I did not understand" as though the
    operator had spoken badly.
    """
    import requests
    try:
        r = requests.post(
            LLM_URL,
            json={"messages": [{"role": "user", "content": "ping"}],
                  "max_tokens": 1,
                  "temperature": 0.0},
            timeout=timeout,
        )
    except Exception as e:
        return False, "LLM unreachable at " + LLM_URL + ": " + str(e)
    if r.status_code != 200:
        return False, "LLM_URL " + LLM_URL + " returned HTTP " + str(r.status_code)
    try:
        r.json()["choices"][0]["message"]["content"]
    except Exception as e:
        return False, "LLM answered but not in OpenAI shape: " + str(e)
    return True, "LLM reachable at " + LLM_URL


